#!/usr/bin/env node
// Provenance gate: complete register entry per persona/sprite production asset;
// dist never ships reference material, original bytes, or audio other than the
// registered Pixabay derivative (ADR-0006). B2: width map.
import { createHash } from "node:crypto";
import {
	existsSync,
	lstatSync,
	readdirSync,
	readFileSync,
	statSync,
} from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

export const REGISTER_SCHEMA_VERSION = 1;
export const OWNER = "Jonathan Soto";
export const OWNER_LICENSE = "owner-created (all rights reserved)";
const ROLES = "principal-persona,sprite-accent,support-avatar".split(",");
const ORIGINS = "owner-created,external".split(",");
const EXTERNAL_LICENSES = "CC0,MIT".split(",");
const AUDIO_EXT = ".mp3,.ogg,.wav,.m4a,.flac".split(",");
const FIELDS =
	"file,origin-class,license,usage-role,creator,commercial-use,modification".split(
		",",
	);
const EXTRA = "source-url,attribution".split(",");

// Resolve a transitive pnpm-store dep (js-yaml, sharp) without new dependencies.
export function requireFromStore(pkg) {
	const store = join(ROOT, "node_modules", ".pnpm");
	let entries = readdirSync(store).filter((d) => d.startsWith(`${pkg}@`));
	if (entries.length === 0)
		throw new Error(`store dependency not found: ${pkg}`);
	if (pkg === "sharp") {
		try {
			const types = createRequire(join(ROOT, "package.json"))(
				"@types/node/package.json",
			).version;
			entries = entries.filter((d) => d.includes(`@types+node@${types}`));
		} catch {
			// Fall through to the first entry.
		}
	}
	const req = createRequire(
		join(store, entries[0], "node_modules", pkg, "package.json"),
	);
	return req(pkg);
}

function loadYamlFile(file) {
	return requireFromStore("js-yaml").load(readFileSync(file, "utf8"));
}

export function assetPath(assetsDir, file) {
	const dir = file.startsWith("persona_") ? "persona" : "sprites";
	return join(assetsDir, dir, file);
}

function sha256(path) {
	return createHash("sha256").update(readFileSync(path)).digest("hex");
}

export function loadRegister(file) {
	const raw = loadYamlFile(file);
	if (!raw || !Array.isArray(raw.register))
		throw new Error(`malformed register: ${file}`);
	return {
		version: raw["schema-version"],
		entries: raw.register,
		music: Array.isArray(raw.music) ? raw.music : [],
	};
}

// Licensed-music contract (ADR-0006): the register's music section must carry
// the full provenance metadata and a committed derivative whose sha256 matches
// derivative-sha256 (regenerated by scripts/optimize-audio.mjs — CI never runs
// ffmpeg, so the recorded hash is what the gate verifies).
export function validateMusic(register, root) {
	const errors = [];
	const fail = (msg) => errors.push(msg);
	if (register.music.length === 0) return errors;
	for (const [index, entry] of register.music.entries()) {
		const where = `music[${index}]`;
		for (const field of [
			"title",
			"creator",
			"source-url",
			"license",
			"acquisition-date",
			"commercial-use",
			"modification",
			"standalone-redistribution",
			"source-path",
			"derivative-path",
			"derivative-format",
			"derivative-sha256",
		]) {
			if (
				entry[field] === undefined ||
				entry[field] === null ||
				entry[field] === ""
			)
				fail(`${where}: missing ${field}`);
		}
		if (entry["commercial-use"] !== "permitted")
			fail(`${where}: commercial-use must be permitted`);
		if (entry.modification !== "permitted")
			fail(`${where}: modification must be permitted`);
		if (entry["standalone-redistribution"] !== false)
			fail(`${where}: standalone-redistribution must be false`);
		if (entry["derivative-format"] !== "mp3")
			fail(`${where}: derivative-format must be mp3`);
		const derivative = join(root, entry["derivative-path"]);
		if (!existsSync(derivative)) {
			fail(
				`${where}: derivative missing on disk (${entry["derivative-path"]})`,
			);
			continue;
		}
		const hash = sha256(derivative);
		if (hash !== entry["derivative-sha256"])
			fail(
				`${where}: derivative sha256 ${hash} does not match registered ${entry["derivative-sha256"]} (regenerate with scripts/optimize-audio.mjs)`,
			);
	}
	return errors;
}

export function validateRegister(register, assetsDir) {
	const errors = [];
	const fail = (msg) => errors.push(msg);
	if (register.version !== REGISTER_SCHEMA_VERSION) {
		fail(`schema-version ${register.version} unsupported`);
	}
	const byFile = new Map();
	for (const entry of register.entries) {
		const { file } = entry;
		if (!file) {
			fail("entry missing file");
			continue;
		}
		if (byFile.has(file)) fail(`${file}: duplicate entry`);
		byFile.set(file, entry);
		const origin = entry["origin-class"];
		if (!ORIGINS.includes(origin))
			fail(`${file}: unknown origin-class ${origin}`);
		for (const field of [...FIELDS, ...(origin === "external" ? EXTRA : [])]) {
			if (!entry[field]) fail(`${file}: missing ${field}`);
		}
		if (!ROLES.includes(entry["usage-role"]))
			fail(`${file}: unknown usage-role ${entry["usage-role"]}`);
		if (origin === "owner-created") {
			if (entry.license !== OWNER_LICENSE)
				fail(`${file}: unknown license ${entry.license}`);
			if (entry.creator !== OWNER) fail(`${file}: creator must be ${OWNER}`);
			if (entry["commercial-use"] !== "permitted")
				fail(`${file}: commercial-use must be permitted`);
			if (entry.modification !== "permitted")
				fail(`${file}: modification must be permitted`);
		} else if (!EXTERNAL_LICENSES.includes(entry.license)) {
			fail(`${file}: external license must be CC0 or MIT`);
		}
	}
	// B3 one-way rename: assets/icon MUST be absent (dir, file, or symlink —
	// lstat does not follow links, so a dangling symlink is caught too).
	try {
		if (lstatSync(join(assetsDir, "icon")))
			fail("assets/icon must not exist (migrated to assets/sprites)");
	} catch {
		// Absent — required state.
	}
	for (const sub of ["persona", "sprites"]) {
		if (!existsSync(join(assetsDir, sub))) continue;
		for (const file of readdirSync(join(assetsDir, sub))) {
			if (!byFile.has(file)) fail(`${file}: unregistered production asset`);
		}
	}
	for (const file of byFile.keys()) {
		if (!existsSync(assetPath(assetsDir, file)))
			fail(`${file}: file missing on disk`);
	}
	return errors;
}

export function scanDist(distDir, originals, allowedAudio = "") {
	const errors = [];
	if (!existsSync(distDir)) return errors;
	const walk = (dir) => {
		for (const name of readdirSync(dir)) {
			const path = join(dir, name);
			if (statSync(path).isDirectory()) {
				walk(path);
				continue;
			}
			if (/(^|[\\/])(mockup|asset_sheet|example)([_.\\/]|$)/.test(path)) {
				errors.push(`${path}: forbidden reference path`);
			}
			if (AUDIO_EXT.includes(name.slice(name.lastIndexOf(".")))) {
				// ADR-0006: the ONLY audio allowed in dist is the registered
				// derivative (public/audio/background.mp3 → dist/audio/…);
				// everything else is rejected.
				const rel = relative(distDir, path);
				if (rel !== allowedAudio) errors.push(`${path}: audio in dist`);
			}
			const hash = sha256(path);
			for (const [file, h] of originals) {
				if (hash === h) errors.push(`${path}: matches original ${file}`);
			}
		}
	};
	walk(distDir);
	return errors;
}

function main() {
	const assetsDir = join(ROOT, "assets");
	const originals = new Map();
	for (const sub of ["persona", "sprites"]) {
		for (const file of readdirSync(join(assetsDir, sub))) {
			originals.set(file, sha256(join(assetsDir, sub, file)));
		}
	}
	const errors = [];
	let entries = 0;
	let allowedAudio = "";
	try {
		const register = loadRegister(join(assetsDir, "PROVENANCE.yaml"));
		entries = register.entries.length;
		errors.push(...validateRegister(register, assetsDir));
		errors.push(...validateMusic(register, ROOT));
		// The one audio file dist may ship: the registered derivative
		// (public/ → dist/ copy, so its dist-relative path is audio/<file>).
		const derivative = register.music[0]?.["derivative-path"] ?? "";
		allowedAudio = derivative.replace(/^public\//, "");
	} catch (err) {
		errors.push(`register: ${err.message}`);
	}
	errors.push(...scanDist(join(ROOT, "dist"), originals, allowedAudio));
	if (errors.length > 0) {
		for (const error of errors) console.error(`provenance gate: ${error}`);
		console.error(`provenance gate: FAILED (${errors.length} violation(s))`);
		process.exit(1);
	}
	console.log(
		`provenance gate: OK (${entries} entries, ${originals.size} originals, ${
			allowedAudio ? `audio ${allowedAudio}` : "no audio"
		})`,
	);
}

if (import.meta.main || process.argv[1] === fileURLToPath(import.meta.url)) {
	main();
}
